# Numbers
# The two common types of numbers in Python are:

# 1. Integers
# Integers are numbers without decimal parts. They can be positive, negative, or zero. Examples include 5, -11, 0 and 12.

# 2. Floating-Point Numbers
# Floating-point numbers contain decimal points. Like integers, they can also be positive, negative, or zero. Examples include 2.5, 6.76, 0.0, and -9.45.


print(10)
print(9.5)

# Performing Calculations

