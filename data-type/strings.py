# Strings

# In Python, text wrapped inside quotation marks are called strings.

"This is a string."
'This is also a string.'

# Strings are Fixed Values
# Like numbers, strings are also fixed values.

# For example, "Python" is equal to 'Python', but it's not equal to "python" or "Python " (extra spaces and capitalization matter!).

# Be mindful of extra spaces or differences in capitalization during practice exercises, as they can cause the exercise to fail.

print("This is a string")